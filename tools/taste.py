"""Taste model: likes/dislikes -> per-attribute scores -> weighted plan for the next batch.

Each design has attrs {format, art, subject, humor, palette}. A vote of +1/-1 counts toward every
attribute value of that design. score = (likes - dislikes) / (likes + dislikes + 2), so it is
shrunk toward 0 until there are several votes. Sampling weight = exp(2.2 * score), so a liked value
is picked ~9x more often than a disliked one, and values with no votes stay at weight 1
(they keep being explored).

CLI: py tools/taste.py report | plan [--n 10] [--track personal|sell|auto]
"""
import json, math, random, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DIMS = ["format", "art", "subject", "humor", "palette"]
VOCAB = {
    "format": ["badge", "band", "game-ui", "sign", "label", "poster", "crest", "comic", "portrait", "mascot",
               "typographic", "pixel-screen", "patches", "tarot"],
    "art": ["retro-70s", "80s-synth", "pixel", "woodcut", "kawaii", "comic", "metal", "vintage-litho", "neon",
            "minimal", "anime", "pop-art", "grunge", "deco", "rubber-hose", "folk", "ornate", "retro-ad"],
    "humor": ["quote", "absurd", "dark", "wholesome", "meta", "gamer", "sassy"],
    "palette": ["pink-gold", "neon", "warm-retro", "earthy", "mono", "primary", "pastel", "dark-red"],
}
SUBJECTS = {  # fan art may use names; sellable designs only generic subjects
    "personal": ["carl", "donut", "mongo", "mordecai", "katia", "samantha", "prepotente", "zev", "system", "trio", "dungeon"],
    "sell": ["cat", "dino", "crawler", "dungeon", "monster", "system"],
}
SHARPNESS = 2.2
EXPLORE = 0.2  # share of slot attributes picked uniformly at random


def load():
    designs = json.loads((ROOT / "designs.json").read_text(encoding="utf-8"))
    fb = ROOT / "feedback.json"
    votes = json.loads(fb.read_text(encoding="utf-8")) if fb.exists() else {}
    return designs, votes


def scores(designs, votes):
    """{dim: {value: {"like": n, "dislike": n, "score": s}}} plus a track entry."""
    out = {d: {} for d in DIMS + ["track"]}
    for d in designs:
        v = (votes.get(d["id"]) or {}).get("vote", 0)
        if not v:
            continue
        pairs = [(k, d.get("attrs", {}).get(k)) for k in DIMS] + [("track", d["track"])]
        for dim, val in pairs:
            if not val:
                continue
            e = out[dim].setdefault(val, {"like": 0, "dislike": 0})
            e["like" if v > 0 else "dislike"] += 1
    for dim in out.values():
        for e in dim.values():
            e["score"] = round((e["like"] - e["dislike"]) / (e["like"] + e["dislike"] + 2), 3)
    return out


def weight(sc, dim, val):
    return math.exp(SHARPNESS * sc.get(dim, {}).get(val, {}).get("score", 0))


def pick(sc, dim, options, rng):
    if rng.random() < EXPLORE:
        return rng.choice(options)
    ws = [weight(sc, dim, o) for o in options]
    return rng.choices(options, ws)[0]


def plan(n=10, track="auto", seed=None):
    designs, votes = load()
    sc = scores(designs, votes)
    rng = random.Random(seed)
    seen = {tuple(d.get("attrs", {}).get(k) for k in ("format", "art", "subject")) for d in designs}
    slots = []
    for _ in range(n):
        t = track if track in ("sell", "personal") else pick(sc, "track", ["personal", "sell"], rng)
        for _try in range(30):
            s = {"track": t, "format": pick(sc, "format", VOCAB["format"], rng), "art": pick(sc, "art", VOCAB["art"], rng),
                 "subject": pick(sc, "subject", SUBJECTS[t], rng), "humor": pick(sc, "humor", VOCAB["humor"], rng),
                 "palette": pick(sc, "palette", VOCAB["palette"], rng)}
            key = (s["format"], s["art"], s["subject"])
            if key not in seen:
                break
        seen.add(key)
        slots.append(s)
    return slots


def examples(designs, votes, sign, k=8):
    hit = [d for d in designs if (votes.get(d["id"]) or {}).get("vote") == sign]
    hit.sort(key=lambda d: (votes[d["id"]].get("ts", 0)), reverse=True)
    return hit[:k]


def report_md():
    designs, votes = load()
    sc = scores(designs, votes)
    nl = sum(1 for v in votes.values() if v.get("vote") == 1)
    nd = sum(1 for v in votes.values() if v.get("vote") == -1)
    L = ["# Taste profile (auto-generated by tools/taste.py; do not edit)", "",
         f"{nl} likes, {nd} dislikes across {len(designs)} designs.", ""]
    for dim in ["track"] + DIMS:
        ranked = sorted(sc[dim].items(), key=lambda kv: kv[1]["score"], reverse=True)
        if not ranked:
            continue
        L.append(f"## {dim}")
        for val, e in ranked:
            L.append(f"- {val}: score {e['score']:+.2f} ({e['like']} up, {e['dislike']} down)")
        L.append("")
    for sign, head in ((1, "Liked"), (-1, "Disliked")):
        ex = examples(designs, votes, sign)
        if ex:
            L.append(f"## {head} designs (most recent first)")
            for d in ex:
                note = votes[d["id"]].get("note", "").strip()
                L.append(f"- {d['title']} ({d['style']}): {d['hook']}" + (f" | User note: \"{note}\"" if note else ""))
            L.append("")
    return "\n".join(L)


def write_report():
    p = ROOT / "image-prompts" / "TASTE.md"
    p.write_text(report_md(), encoding="utf-8")
    return p


if __name__ == "__main__":
    cmd = sys.argv[1] if len(sys.argv) > 1 else "report"
    if cmd == "plan":
        n = int(sys.argv[sys.argv.index("--n") + 1]) if "--n" in sys.argv else 10
        tr = sys.argv[sys.argv.index("--track") + 1] if "--track" in sys.argv else "auto"
        print(json.dumps(plan(n, tr), indent=1))
    else:
        print(write_report().read_text(encoding="utf-8"))
